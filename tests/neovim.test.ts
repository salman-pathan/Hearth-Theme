import test from "node:test";
import assert from "node:assert/strict";

import { themeOutputs } from "../src/config/outputs.js";

import {
  createNeovimHighlights,
  createNeovimTheme,
} from "../src/adapters/neovim/index.js";

import { createColorRegistry } from "../src/tokens/registry.js";
import { hearthTokens } from "../src/tokens/hearth.js";
import { resolveTokens } from "../src/tokens/resolver.js";

const theme = resolveTokens(hearthTokens, createColorRegistry());

test("maps editor background correctly", () => {
  const highlights = createNeovimHighlights(theme);

  assert.equal(highlights.Normal.bg, theme["editor.background"]);

  assert.equal(highlights.Normal.fg, theme["editor.foreground"]);
});

test("maps Tree-sitter highlighting", () => {
  const highlights = createNeovimHighlights(theme);

  assert.deepEqual(highlights["@function"], { link: "Function" });

  assert.equal(highlights["@variable.parameter"].fg, theme["syntax.parameter"]);
});

test("maps diagnostics correctly", () => {
  const highlights = createNeovimHighlights(theme);

  assert.equal(highlights.DiagnosticError.fg, theme["diagnostic.error"]);

  assert.equal(highlights.DiagnosticWarn.fg, theme["diagnostic.warning"]);
});

test("generates a Neovim Lua module", () => {
  const lua = createNeovimTheme(theme);

  assert.match(lua, /local M = \{\}/);
  assert.match(lua, /vim\.api\.nvim_set_hl/);
  assert.match(lua, /return M/);
  assert.ok(lua.includes(theme["editor.background"]));
});

test("Neovim output is raw Lua, not JSON", () => {
  const output = themeOutputs.find((item) => item.path.endsWith("theme.lua"));

  assert.ok(output, "Neovim output must be registered");

  const lua = output.generate(theme);

  assert.ok(
    lua.startsWith("-- Generated by Hearth Theme"),
    "Generated Lua must start with a Lua comment",
  );

  assert.match(lua, /local M = \{\}/);
  assert.match(lua, /return M\s*$/);

  assert.doesNotMatch(
    lua,
    /^"/,
    "Lua source must not be wrapped in JSON quotes",
  );
});
